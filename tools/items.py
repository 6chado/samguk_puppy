def meat(P0, E):
    # 전체를 가운데(24,24) 기준 시계방향 45도 회전
    c, sn = math.cos(math.radians(45)), math.sin(math.radians(45))

    def P(pts, col):
        P0([(24 + (x - 24) * c - (y - 24) * sn, 24 + (x - 24) * sn + (y - 24) * c) for x, y in pts], col)

    # 뼈 (뒤): 굵고 또렷하게, 양 끝으로 살짝만 (전체의 약 20%)
    bone, bone_d = (240, 226, 196), (196, 174, 140)
    P([(4, 21.6), (44, 21.6), (44, 26.4), (4, 26.4)], flat(bone))
    P([(4, 24.6), (44, 24.6), (44, 26.4), (4, 26.4)], flat(bone_d))
    for x, sx in ((3.4, -1), (44.6, 1)):
        for dy in (-2.9, 2.9):
            P(ngon(x, 24 + dy, 3.0, 3.0, 6, 0.3), flat(bone_d))
            P(ngon(x - 0.4 * sx, 24 + dy - 0.5, 2.3, 2.3, 6, 0.3), flat(bone))
    # 고기 (약 80%): 옆으로 길쭉한 덩어리
    P([(8, 22), (10.5, 17), (17, 14.5), (31, 14.5), (37.5, 17), (40, 22),
       (38.5, 28.5), (32, 32.5), (16, 32.5), (9.5, 28.5)], (196, 86, 62))
