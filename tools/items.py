def guandao(P0, E):
    """청룡언월도 (참고 자료 모양):
    길고 넓게 휜 칼날 - 위쪽 날은 매끈한 큰 곡선, 아래쪽 칼등은 톱니처럼 뾰족뾰족,
    끝은 뒤로 휘어 뾰족. 밑동은 용머리가 자루와 딱 맞게 물고 있음 (옆으로 안 삐져나감).
    칼날 기준 좌표로 그린 뒤 왼쪽 위를 향하게 45도 눕힘."""
    k = 1.0
    ox, oy = 26.1, 26.1
    c, sn = math.cos(math.radians(-45)), math.sin(math.radians(-45))

    def P(pts, col):
        P0([(ox + (x * c - y * sn) * k, oy + (x * sn + y * c) * k) for x, y in pts], col)

    steel, steel_d, steel_l = (214, 228, 236), (162, 180, 196), (246, 250, 252)
    gold, gold_d = (236, 190, 78), (190, 140, 50)

    # 자루 (짧게)
    P([(-1.2, 2.5), (1.2, 2.5), (1.2, 21.5), (-1.2, 21.5)], flat((150, 92, 52)))
    P([(0.2, 2.5), (1.2, 2.5), (1.2, 21.5), (0.2, 21.5)], flat((112, 66, 36)))
    P([(-1.5, 21), (1.5, 21), (1.2, 23.5), (-1.2, 23.5)], flat(gold))

    # 칼날: 오른쪽 = 큰 곡선 날, 왼쪽 = 매끈한 칼등
    edge = [(2.2, 0), (4.5, -4), (6.2, -9), (6.8, -14), (6.2, -19), (4.2, -23.5), (1, -27), (-3.5, -29.5)]
    # 칼등: 아래쪽을 초록 용 입의 왼쪽 끝까지 당겨서 넓힘 (길이·기울기는 그대로)
    spine = [(-2.4, -26), (-1.6, -22), (-1.3, -15), (-1.0, -7.5), (-1.7, -3.0), (-2.4, -1.4), (-1.4, 0)]
    P(edge + spine, flat(steel))
    inner = [(1.2, -25), (3.4, -22.4), (4.8, -18.6), (5.2, -14), (4.6, -9.2), (3.2, -4.6), (1.2, -0.6)]
    P(edge[:7] + list(reversed(inner)), flat(steel_d))
    P([(-3.5, -29.5), (-2.4, -26), (-1.6, -22), (-1.2, -15), (-1.0, -7.5), (-1.7, -3.0), (-2.4, -1.4),
       (-0.6, -1.4), (0.2, -7.5), (0.2, -15), (-0.4, -22), (-1.4, -26.4)], flat(steel_l))
    # 칼날 가운데 새긴 청룡 무늬 (화면 기준 오른쪽으로 아주 살짝 → 이 좌표계에선 (+0.4, +0.4))
    zig = [(1.4, -21), (2.6, -18), (1.6, -15), (2.8, -12), (1.8, -9), (2.8, -6),
           (2.0, -6), (1.0, -9), (2.0, -12), (0.8, -15), (1.8, -18), (0.6, -21)]
    zcx = sum(x for x, _ in zig) / len(zig)
    zcy = sum(y for _, y in zig) / len(zig)
    zig = [(zcx + (x - zcx) * 0.85, zcy + (y - zcy) * 0.85) for x, y in zig]   # 15% 축소 (가운데 기준)
    P([(x + 0.9, y + 0.4) for x, y in zig], flat((52, 148, 84)))

    # 용머리 코등이: 자루 폭에 딱 맞게, 칼날 밑동을 감쌈
    P([(-2.4, -1.4), (2.6, -1.4), (2.4, 3), (-2.2, 3)], flat(gold))
    P([(0.6, -1.4), (2.6, -1.4), (2.4, 3), (0.6, 3)], flat(gold_d))
    P([(-2.4, -1.4), (2.6, -1.4), (2.0, -3.4), (-1.6, -3.0)], flat((52, 148, 84)))
    P(ngon(-0.6, 0.8, 0.7, 0.7, 6), flat((52, 148, 84)))

    # 붉은 술: 칼날과 자루가 만나는 곳에 매달려 아래로 늘어짐
    dx, dy = -0.707, 0.707          # 화면 아래 방향 (이 좌표계 기준)
    px, py = 0.707, 0.707           # 그 옆 방향
    ax, ay = -2.0, 1.0              # 매다는 곳 (코등이 왼쪽)

    def at(t, w):
        return (ax + dx * t + px * w, ay + dy * t + py * w)
    P([at(0, -0.35), at(0, 0.35), at(2.4, 0.35), at(2.4, -0.35)], flat((206, 52, 52)))       # 끈
    P(ngon(*at(2.6, 0), 0.9, 0.9, 6), flat((236, 190, 78)))                                   # 매듭
    P([at(3.2, -0.8), at(3.2, 0.8), at(9.0, 1.9), at(9.6, 0), at(9.0, -1.9)], flat((214, 56, 56)))
    P([at(3.2, 0), at(3.2, 0.8), at(9.0, 1.9), at(9.6, 0)], flat((166, 36, 40)))


