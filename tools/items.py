OUTLINE = (92, 62, 46)   # 밝은 배경에서도 흰 뼈·칼날이 보이게 두르는 진한 테두리


def render(fn, size=192):
    from PIL import ImageFilter
    big = size * 4
    pad = big // 24
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    s = (big - pad * 2) / 48
    d = FacetDraw(img, s)
    fn(lambda pts, col: d.polygon([(pad + x * s, pad + y * s) for x, y in pts], col), None)
    # 실루엣 바깥으로 테두리 (최종 크기에서 약 2px)
    alpha = img.getchannel("A")
    grow = int(size / 192 * 2.2 * 4) * 2 + 1
    ring = alpha.filter(ImageFilter.MaxFilter(grow))
    out = Image.new("RGBA", img.size, (*OUTLINE, 0))
    out.putalpha(ring)
    out.alpha_composite(img)
    return out.resize((size, size), Image.LANCZOS)


