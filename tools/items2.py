def clover(P, E):
    """네잎클로버: 하트 모양 잎 4장 + 줄기"""
    P([(23.4, 25), (25.0, 25), (31.0, 44), (29.0, 44.6)], (70, 140, 62))
    leaf_cols = [(112, 196, 92), (78, 158, 68), (112, 196, 92), (78, 158, 68)]
    for k in range(4):
        ang = math.radians(-45 + 90 * k)
        ca, sa = math.cos(ang), math.sin(ang)
        # 하트 잎: 중심에서 바깥으로 뻗은 두 둥근 덩어리
        for side in (-1, 1):
            ox, oy = 10.4 * ca - 3.6 * side * sa, 10.4 * sa + 3.6 * side * ca
            P(ngon(24 + ox, 23 + oy, 4.4, 4.4, 7, k * 0.5 + side), leaf_cols[k])
        P([(24, 23), (24 + 7 * ca - 5.6 * sa, 23 + 7 * sa + 5.6 * ca), (24 + 12.4 * ca, 23 + 12.4 * sa),
           (24 + 7 * ca + 5.6 * sa, 23 + 7 * sa - 5.6 * ca)], leaf_cols[k])
        # 잎맥
        P([(24 + 2 * ca - 0.4 * sa, 23 + 2 * sa + 0.4 * ca), (24 + 11 * ca, 23 + 11 * sa),
           (24 + 2 * ca + 0.4 * sa, 23 + 2 * sa - 0.4 * ca)], flat((168, 224, 140)))
    P(ngon(24, 23, 1.8, 1.8, 6), flat((70, 140, 62)))


